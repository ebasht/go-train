export const TRACK_LIST = [middle, senior]

export const TRACKS = Object.fromEntries(TRACK_LIST.map((track) => [track.id, track]))

export function flatten(track) {
  return track.weeks.flatMap((week, weekIndex) =>
    week.items.map((item, itemIndex) => ({
      ...item,
      id: `${weekIndex}-${itemIndex}`,
      weekIndex,
      itemIndex,
    })),
  )
}
